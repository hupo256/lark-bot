/**
 * 开跑前群里那句（「收到」/「记下了」）的出口校验（10-23 #74，并入 #14 预案的「承诺结果」闸）：
 * 这句话出自分类器——它只读了消息、什么都没查，只能说收到了什么、接下来做什么；不得替人下结论：
 *   · 对方系统 / 环境的状态（「pre 发帖和评论还没开」——实测 pre 后端发帖正常，Encone 说的是 web 端还不能发）；
 *   · 需求范围、做不做（「web 发帖先保持『即将上线』」「前端不用改」）；
 *   · 根因归属（「是后端的问题」）；承诺结果（「一定 / 保证 / 我来修」，原 #14）。
 * 命中就不用这句，回落中性固定句；结论只能来自工单执行后的核实结果。负责人私聊里自己定的回话（privateOrigin）不查。
 */

const CONCLUSION_RES = [
  /(还|仍|都|也)?(没|未|不能|无法|不支持)(开|开通|开放|上线|部署|生效|修|好|通|实现)/,
  /先保持|保持.{0,6}(不变|原样|现状|即将上线)|维持|暂(不|缓)(做|改|接|处理)?|不(用|需要?|必)(改|做|动|处理|接|管)|无需|不做|二期|(不在|超出).{0,4}范围/,
  /是(后端|服务端|接口|App|产品|运维|前端)(那边)?的?(问题|bug|锅|事)/i,
  /一定|保证|肯定(能|会)|马上(就)?(好|修好)|我来修/,
]

// 返回能发的那句；带结论 / 空 → null（调用方回落固定句）。
export const vetLeadText = ({ task = null, text }) => {
  const said = String(text || '').trim()
  if (!said) return null
  if (task?.privateOrigin) return said
  return CONCLUSION_RES.some((re) => re.test(said)) ? null : said
}
